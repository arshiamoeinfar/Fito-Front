export function getPostBySlug(slug) {
  return posts.find((p) => p.slug === slug) || null;
}

export function getPostsByCategorySlug(slug) {
  return posts.filter((p) => p.category_slug === slug);
}

export function getRelatedPosts(post, limit = 3) {
  if (!post) return [];
  const byId = (post.related_post_ids || [])
    .map((id) => posts.find((p) => p.id === id))
    .filter(Boolean);
  const rest = posts.filter((p) => p.id !== post.id && !byId.some((b) => b.id === p.id));
  return [...byId, ...rest].slice(0, limit);
}

